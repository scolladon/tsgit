#!/usr/bin/env node
/**
 * Generates `src/domain/pretty/utf8-width-tables.ts` from git's `unicode-width.h`.
 *
 * The committed output is the source of truth at runtime; this script only
 * regenerates it when git's tables move. It never touches the network:
 * fetch the header once, then point the script at the local copy.
 *
 *   curl -fsSL https://raw.githubusercontent.com/git/git/v2.55.0/unicode-width.h -o unicode-width.h
 *   node --experimental-strip-types tooling/gen-utf8-width.ts unicode-width.h
 *   ./node_modules/.bin/biome format --write src/domain/pretty/utf8-width-tables.ts
 *
 * Each table is emitted as a flat `[first0, last0, first1, last1, ...]` array
 * to keep the bundle small.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const OUTPUT_PATH = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/domain/pretty/utf8-width-tables.ts',
);
const TABLE_PATTERN = /static const struct interval (\w+)\[\] = \{([\s\S]*?)\n\};/g;
const INTERVAL_PATTERN = /\{\s*0x([0-9A-Fa-f]+)\s*,\s*0x([0-9A-Fa-f]+)\s*\}/g;

const parseIntervals = (body: string): readonly number[] =>
  [...body.matchAll(INTERVAL_PATTERN)].flatMap(([, first, last]) => [
    Number.parseInt(first as string, 16),
    Number.parseInt(last as string, 16),
  ]);

const parseTables = (header: string): ReadonlyMap<string, readonly number[]> =>
  new Map(
    [...header.matchAll(TABLE_PATTERN)].map(([, name, body]) => [
      name as string,
      parseIntervals(body as string),
    ]),
  );

const requireTable = (tables: ReadonlyMap<string, readonly number[]>, name: string) => {
  const table = tables.get(name);
  if (table === undefined || table.length === 0) {
    throw new Error(`unicode-width.h has no usable "${name}" table`);
  }
  return table;
};

const renderTable = (exportName: string, table: readonly number[]): string => {
  const cells = table.map((codePoint) => `0x${codePoint.toString(16).toUpperCase()}`);
  return `export const ${exportName}: readonly number[] = [${cells.join(', ')}];\n`;
};

const main = (): void => {
  const headerPath = process.argv[2];
  if (headerPath === undefined) {
    throw new Error('usage: gen-utf8-width.ts <path-to-unicode-width.h>');
  }
  const tables = parseTables(readFileSync(headerPath, 'utf8'));
  const output = [
    '// Generated by tooling/gen-utf8-width.ts from git unicode-width.h. Do not edit.',
    '// Flat [first, last, first, last, ...] inclusive code point intervals.',
    renderTable('ZERO_WIDTH_INTERVALS', requireTable(tables, 'zero_width')),
    renderTable('DOUBLE_WIDTH_INTERVALS', requireTable(tables, 'double_width')),
  ].join('\n');
  writeFileSync(OUTPUT_PATH, output);
};

main();
